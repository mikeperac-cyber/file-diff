using System.Globalization;
using System.Text;
using FileDiff.Core.Diffing;
using FileDiff.Core.Util;

namespace FileDiff.Core.Export;

/// <summary>
/// Self-contained HTML report: one file, no external references, so it can be e-mailed, archived
/// or opened years later without the app.
/// </summary>
public static class HtmlExporter
{
    private static readonly UTF8Encoding Utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

    public static string Build(ExportRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);

        var diff = request.Diff;
        var builder = new StringBuilder(64 * 1024);

        builder.Append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
        builder.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        builder.Append("<title>").Append(Escape($"Changes in {LeafName(diff.RootPath)}")).Append("</title>\n");
        builder.Append("<style>\n").Append(Css).Append("</style>\n</head>\n<body>\n");

        WriteHeader(builder, request);
        WriteIndex(builder, request);

        var anchor = 0;
        foreach (var change in diff.Changes)
        {
            anchor++;
            WriteFileSection(
                builder,
                change,
                request.GetDocument(change),
                "file-" + anchor.ToString(CultureInfo.InvariantCulture));
        }

        builder.Append("<footer>Generated by ").Append(Escape(request.AppName)).Append(" on ")
            .Append(DateTimeOffset.Now.ToString("yyyy-MM-dd HH:mm:ss zzz", CultureInfo.InvariantCulture))
            .Append("</footer>\n</body>\n</html>\n");

        return builder.ToString();
    }

    public static void WriteTo(ExportRequest request, string path) =>
        File.WriteAllText(path, Build(request), Utf8NoBom);

    private static void WriteHeader(StringBuilder builder, ExportRequest request)
    {
        var diff = request.Diff;

        builder.Append("<header>\n");
        builder.Append("<h1>Changes in <code>").Append(Escape(LeafName(diff.RootPath))).Append("</code></h1>\n");
        builder.Append("<p class=\"root\">").Append(Escape(diff.RootPath)).Append("</p>\n");
        builder.Append("<p class=\"compare\">Comparing <strong>").Append(Escape(request.BaselineLabel))
            .Append("</strong> with <strong>").Append(Escape(request.TargetLabel)).Append("</strong></p>\n");

        if (!string.IsNullOrWhiteSpace(request.Note))
        {
            builder.Append("<p class=\"note\">").Append(Escape(request.Note)).Append("</p>\n");
        }

        builder.Append("<ul class=\"summary\">\n");
        AppendChip(builder, "added", diff.AddedCount, "added");
        AppendChip(builder, "modified", diff.ModifiedCount, "modified");
        AppendChip(builder, "removed", diff.RemovedCount, "deleted");
        AppendChip(builder, "moved", diff.MovedCount, "moved");
        AppendChip(builder, "unchanged", diff.UnchangedCount, "unchanged");
        builder.Append("</ul>\n</header>\n");
    }

    private static void AppendChip(StringBuilder builder, string kind, int count, string label) =>
        builder.Append("<li class=\"chip ").Append(kind).Append("\"><span class=\"n\">")
            .Append(count.ToString("N0", CultureInfo.InvariantCulture)).Append("</span> ")
            .Append(Escape(label)).Append("</li>\n");

    private static string KindClass(FileChange change) => change.Kind switch
    {
        ChangeKind.Added => "added",
        ChangeKind.Removed => "removed",
        ChangeKind.Modified => "modified",
        _ => "moved",
    };

    private static string LeafName(string path)
    {
        var trimmed = path.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
        var leaf = Path.GetFileName(trimmed);
        return string.IsNullOrEmpty(leaf) ? path : leaf;
    }

    public static string Escape(string? value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return string.Empty;
        }

        var builder = new StringBuilder(value.Length + 16);

        foreach (var c in value)
        {
            switch (c)
            {
                case '&': builder.Append("&amp;"); break;
                case '<': builder.Append("&lt;"); break;
                case '>': builder.Append("&gt;"); break;
                case '"': builder.Append("&quot;"); break;
                case '\'': builder.Append("&#39;"); break;
                default: builder.Append(c); break;
            }
        }

        return builder.ToString();
    }

    private static void WriteIndex(StringBuilder builder, ExportRequest request)
    {
        var diff = request.Diff;

        if (!diff.HasChanges)
        {
            builder.Append("<p class=\"empty\">No differences — every file matches the baseline byte for byte.</p>\n");
            return;
        }

        builder.Append("<section class=\"index\">\n<h2>Changed files</h2>\n");
        builder.Append("<table>\n<thead><tr><th>Change</th><th>Path</th><th>Size</th><th>Lines</th></tr></thead>\n<tbody>\n");

        var anchor = 0;
        foreach (var change in diff.Changes)
        {
            anchor++;
            var id = "file-" + anchor.ToString(CultureInfo.InvariantCulture);
            var grew = change.Kind is ChangeKind.Modified or ChangeKind.Moved;

            builder.Append("<tr><td><span class=\"badge ").Append(KindClass(change)).Append("\">")
                .Append(Escape(change.KindLabel)).Append("</span></td>");

            builder.Append("<td><a href=\"#").Append(id).Append("\">").Append(Escape(change.Path)).Append("</a>");

            if (change.Kind == ChangeKind.Moved && !string.IsNullOrEmpty(change.OldPath))
            {
                builder.Append("<br><span class=\"from\">from ").Append(Escape(change.OldPath)).Append("</span>");
            }

            builder.Append("</td><td class=\"num\">");
            builder.Append(PathUtil.FormatBytes(change.Kind == ChangeKind.Added ? change.NewSize : change.OldSize));

            if (grew)
            {
                builder.Append(" → ").Append(PathUtil.FormatBytes(change.NewSize));
            }

            builder.Append("</td><td class=\"num\">");

            if (change.AddedLines.HasValue || change.RemovedLines.HasValue)
            {
                builder.Append("<span class=\"plus\">+").Append(change.AddedLines ?? 0)
                    .Append("</span> <span class=\"minus\">-").Append(change.RemovedLines ?? 0).Append("</span>");
            }
            else
            {
                builder.Append("<span class=\"from\">—</span>");
            }

            builder.Append("</td></tr>\n");
        }

        builder.Append("</tbody>\n</table>\n</section>\n");
    }

    private static void WriteFileSection(
        StringBuilder builder,
        FileChange change,
        FileDiffDocument document,
        string anchor)
    {
        builder.Append("<section class=\"file\" id=\"").Append(anchor).Append("\">\n");
        builder.Append("<h3><span class=\"badge ").Append(KindClass(change)).Append("\">")
            .Append(Escape(change.KindLabel)).Append("</span> <code>").Append(Escape(change.Path)).Append("</code></h3>\n");

        if (change.Kind == ChangeKind.Moved && !string.IsNullOrEmpty(change.OldPath))
        {
            builder.Append("<p class=\"meta\">was <code>").Append(Escape(change.OldPath)).Append("</code></p>\n");
        }

        builder.Append("<p class=\"meta\">")
            .Append(PathUtil.FormatBytes(change.OldSize)).Append(" → ").Append(PathUtil.FormatBytes(change.NewSize));

        if (document.HasContent)
        {
            builder.Append(" · <span class=\"plus\">+").Append(document.AddedLines)
                .Append("</span> <span class=\"minus\">-").Append(document.RemovedLines).Append("</span>")
                .Append(" lines (")
                .Append(document.OldLineCount).Append(" → ").Append(document.NewLineCount)
                .Append(')');

            if (!string.IsNullOrEmpty(document.NewEncoding))
            {
                builder.Append(" · ").Append(Escape(document.NewEncoding));
            }

            if (!string.IsNullOrEmpty(document.NewLineEnding))
            {
                builder.Append(" · ").Append(Escape(document.NewLineEnding));
            }
        }

        builder.Append("</p>\n");

        foreach (var note in document.Notes)
        {
            builder.Append("<p class=\"note\">").Append(Escape(note)).Append("</p>\n");
        }

        if (!document.HasContent)
        {
            builder.Append("<p class=\"skip\">")
                .Append(Escape(document.UnavailableReason ?? "Content is not available."))
                .Append("</p>\n</section>\n");
            return;
        }

        builder.Append("<table class=\"diff\">\n");

        foreach (var hunk in document.Hunks)
        {
            builder.Append("<tr class=\"hunk\"><td class=\"ln\"></td><td class=\"ln\"></td><td class=\"code\">")
                .Append(Escape(hunk.Header)).Append("</td></tr>\n");

            foreach (var line in hunk.Lines)
            {
                builder.Append("<tr class=\"").Append(LineClass(line.Kind)).Append("\">");
                builder.Append("<td class=\"ln\">").Append(Number(line.OldLineNumber)).Append("</td>");
                builder.Append("<td class=\"ln\">").Append(Number(line.NewLineNumber)).Append("</td>");
                builder.Append("<td class=\"code\"><span class=\"marker\">").Append(line.Marker).Append("</span>");

                if (line.HasEmphasis)
                {
                    builder.Append(Escape(line.Prefix))
                        .Append("<span class=\"em\">").Append(Escape(line.Emphasis)).Append("</span>")
                        .Append(Escape(line.Suffix));
                }
                else
                {
                    builder.Append(Escape(line.Text));
                }

                builder.Append("</td></tr>\n");
            }
        }

        builder.Append("</table>\n</section>\n");
    }

    private static string LineClass(DiffLineKind kind) => kind switch
    {
        DiffLineKind.Added => "add",
        DiffLineKind.Removed => "del",
        _ => "ctx",
    };

    private static string Number(int? value) => value?.ToString(CultureInfo.InvariantCulture) ?? string.Empty;

